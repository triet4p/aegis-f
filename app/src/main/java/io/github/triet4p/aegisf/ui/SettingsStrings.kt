    fun protocolName(protocol: HostedProtocol): String = when (protocol) {
        HostedProtocol.GEMINI_GENERATE_CONTENT -> providerProtocolGemini
        HostedProtocol.OPENAI_CHAT_COMPLETIONS -> providerProtocolOpenAiChat
        HostedProtocol.OPENAI_RESPONSES -> providerProtocolOpenAiResponses
    }

    fun reasoningName(effort: HostedReasoningEffort?): String = when (effort) {
        null -> providerReasoningNone
        HostedReasoningEffort.MINIMAL -> reasoningMinimal
        HostedReasoningEffort.LOW -> reasoningLow
        HostedReasoningEffort.MEDIUM -> reasoningMedium
        HostedReasoningEffort.HIGH -> reasoningHigh
    }
